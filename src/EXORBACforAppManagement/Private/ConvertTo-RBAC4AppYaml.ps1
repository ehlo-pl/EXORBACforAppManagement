function ConvertTo-RBAC4AppYaml {
    param(
        [Parameter(Mandatory)]
        [psobject] $Config
    )

    function ConvertTo-RBAC4AppYamlScalar {
        param(
            [AllowNull()]
            [object] $Value
        )

        $text = if ($null -eq $Value) { '' } else { [string]$Value }
        if ($text -match "[`r`n]") {
            throw 'YAML scalar values cannot contain CR or LF characters.'
        }

        $escaped = $text.Replace('\', '\\').Replace('"', '\"')
        return '"' + $escaped + '"'
    }

    $lines = [System.Collections.Generic.List[string]]::new()
    $lines.Add('# RBAC4App configuration — generated by New-RBAC4AppConfig')
    $lines.Add('# Feed to Invoke-RBAC4AppConfig in a session with only ExchangeOnlineManagement connected.')
    # Writes only the keys present on the config object (ConvertTo-RBAC4AppConfig already omits
    # unused/default entries) and skips any that are null, empty strings, or empty lists, so a
    # hand-built config never produces empty fields either. Lists become "- item" sequences.
    function Add-RBAC4AppYamlProperty {
        param(
            [string] $Indent,
            [string] $Name,
            [AllowNull()]
            [object] $Value
        )

        if ($null -eq $Value) { return }
        if ($Value -is [System.Collections.IEnumerable] -and $Value -isnot [string]) {
            $items = @($Value | Where-Object { $null -ne $_ -and [string]$_ -ne '' })
            if ($items.Count -eq 0) { return }
            $lines.Add("$Indent$($Name):")
            foreach ($item in $items) {
                $lines.Add("$Indent  - $(ConvertTo-RBAC4AppYamlScalar $item)")
            }
            return
        }
        if ([string]$Value -eq '') { return }
        $lines.Add("$Indent$($Name): $(ConvertTo-RBAC4AppYamlScalar $Value)")
    }

    foreach ($key in @('SchemaVersion', 'GeneratedAt', 'TenantId')) {
        if ($Config.PSObject.Properties[$key]) { Add-RBAC4AppYamlProperty -Indent '' -Name $key -Value $Config.$key }
    }
    foreach ($section in @('Application', 'Rbac', 'RbacScope')) {
        $sectionValue = if ($Config.PSObject.Properties[$section]) { $Config.$section } else { $null }
        if ($null -eq $sectionValue) { continue }
        $sectionStart = $lines.Count
        foreach ($property in $sectionValue.PSObject.Properties) {
            Add-RBAC4AppYamlProperty -Indent '  ' -Name $property.Name -Value $property.Value
        }
        if ($lines.Count -gt $sectionStart) {
            $lines.Insert($sectionStart, "$($section):")
            $lines.Insert($sectionStart, '')
        }
    }

    return $lines -join [System.Environment]::NewLine
}

Describe 'Invoke-RBAC4AppConfig' {
    BeforeEach {
        Mock -ModuleName EXORBACforAppManagement Get-ConnectionInformation { [pscustomobject]@{ TenantId = 'tenant-1'; UserPrincipalName = 'admin@contoso.com' } }
        Mock -ModuleName EXORBACforAppManagement Get-UnifiedGroup { }
        Mock -ModuleName EXORBACforAppManagement Get-UnifiedGroupLinks { @() }
        Mock -ModuleName EXORBACforAppManagement New-UnifiedGroup { [pscustomobject]@{ DisplayName = 'g'; Alias = 'g' } }
        Mock -ModuleName EXORBACforAppManagement Set-UnifiedGroup { }
        Mock -ModuleName EXORBACforAppManagement Add-UnifiedGroupLinks { }
        Mock -ModuleName EXORBACforAppManagement Get-Recipient { [pscustomobject]@{ PrimarySmtpAddress = 'shared@contoso.com'; DistinguishedName = 'CN=Um365RAo1-Contoso,DC=prod' } }
        Mock -ModuleName EXORBACforAppManagement Get-ManagementScope { }
        Mock -ModuleName EXORBACforAppManagement New-ManagementScope { [pscustomobject]@{ Name = $Name; RecipientFilter = $RecipientRestrictionFilter } }
        Mock -ModuleName EXORBACforAppManagement Set-ManagementScope { }
        Mock -ModuleName EXORBACforAppManagement Get-DistributionGroupMember { @() }
        Mock -ModuleName EXORBACforAppManagement Get-ServicePrincipal { @() }
        Mock -ModuleName EXORBACforAppManagement New-ServicePrincipal { [pscustomobject]@{ DisplayName = 'Contoso_SP' } }
        Mock -ModuleName EXORBACforAppManagement New-ManagementRoleAssignment { [pscustomobject]@{ Name = 'AppMailSend-Contoso' } }
        Mock -ModuleName EXORBACforAppManagement Get-ManagementRoleAssignment { }
        Mock -ModuleName EXORBACforAppManagement Save-RBAC4AppChangeReferenceRecord { Join-Path $TestDrive "$ChangeReference.yaml" }
    }

    It 'provisions scope group, registers SP, and creates role assignment from YAML' {
        $res = Invoke-RBAC4AppConfig -Path $script:configPath -Confirm:$false
        $res.ResolvedDisplay | Should -Be 'Contoso'
        $res.AppId            | Should -Be '11111111-1111-1111-1111-111111111111'
        $res.SpObjectId       | Should -Be '22222222-2222-2222-2222-222222222222'
        $res.Errors           | Should -BeNullOrEmpty
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-UnifiedGroup -Times 1
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ServicePrincipal -Times 1
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementRoleAssignment -Times 1
    }

    It 'reads every config in a multi-config YAML-compatible JSON file' {
        $config = InModuleScope EXORBACforAppManagement -Parameters @{ Content = $script:testYaml } {
            ConvertFrom-RBAC4AppYaml -Content $Content
        }
        $secondConfig = $config | ConvertTo-Json -Depth 6 | ConvertFrom-Json
        $secondConfig.Application.AppId = '33333333-3333-3333-3333-333333333333'
        $secondConfig.Application.SpObjectId = '44444444-4444-4444-4444-444444444444'
        $secondConfig.Application.DisplayName = 'Fabrikam'
        $multiConfigPath = Join-Path $TestDrive 'multi-config.yml'
        Set-Content -LiteralPath $multiConfigPath -Value (ConvertTo-Json -InputObject @($config, $secondConfig) -Depth 6)

        $results = @(Invoke-RBAC4AppConfig -Path $multiConfigPath -Confirm:$false)

        $results.Count | Should -Be 2
        ($results.ResolvedDisplay | Sort-Object) | Should -Be @('Contoso', 'Fabrikam')
        $results.IdentityInput | Should -Be @($multiConfigPath, $multiConfigPath)
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementRoleAssignment -Times 2
    }

    It 'creates a separate scope group and management scope for each role when configured' {
        $separateConfig = Join-Path $TestDrive 'test-config-separate-role-scopes.yml'
        $yaml = $script:testYaml -replace 'SchemaVersion: "3.0"', 'SchemaVersion: "4.0"'
        $yaml = $yaml -replace '    - Application Mail.Send', "    - Application Mail.Send`n    - Application Calendars.Read"
        $yaml = $yaml -replace '  BootstrapMember: GraphAPI-Dummy', "  BootstrapMember: GraphAPI-Dummy`n  ScopeKind: `"Group`"`n  SeparateScopePerRole: `"true`""
        Set-Content $separateConfig -Value $yaml -Encoding UTF8

        $res = Invoke-RBAC4AppConfig -Path $separateConfig -Confirm:$false

        $res.Errors | Should -BeNullOrEmpty
        $res.ScopeGroupNames | Should -Contain 'Um365RAo1-Contoso-AppMailSend'
        $res.ScopeGroupNames | Should -Contain 'Um365RAo1-Contoso-AppCldR'
        $res.ManagementScopeNames | Should -Contain 'MSRAo1P-Contoso-AppMailSend'
        $res.ManagementScopeNames | Should -Contain 'MSRAo1P-Contoso-AppCldR'
        $res.RoleScopes | Should -HaveCount 2
        ($res.RoleScopes | Where-Object Role -eq 'Application Mail.Send').ManagementScopeName |
            Should -Be 'MSRAo1P-Contoso-AppMailSend'
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-UnifiedGroup -Times 1 -ParameterFilter {
            $Name -eq 'Um365RAo1-Contoso-AppMailSend'
        }
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-UnifiedGroup -Times 1 -ParameterFilter {
            $Name -eq 'Um365RAo1-Contoso-AppCldR'
        }
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementScope -Times 1 -ParameterFilter {
            $Name -eq 'MSRAo1P-Contoso-AppMailSend'
        }
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementScope -Times 1 -ParameterFilter {
            $Name -eq 'MSRAo1P-Contoso-AppCldR'
        }
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementRoleAssignment -Times 1 -ParameterFilter {
            $Role -eq 'Application Mail.Send' -and $CustomResourceScope -eq 'MSRAo1P-Contoso-AppMailSend'
        }
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementRoleAssignment -Times 1 -ParameterFilter {
            $Role -eq 'Application Calendars.Read' -and $CustomResourceScope -eq 'MSRAo1P-Contoso-AppCldR'
        }
    }

    It 'honors -WhatIf for all per-role group and scope creations' {
        $separateConfig = Join-Path $TestDrive 'test-config-separate-role-whatif.yml'
        $yaml = $script:testYaml -replace 'SchemaVersion: "3.0"', 'SchemaVersion: "4.0"'
        $yaml = $yaml -replace '    - Application Mail.Send', "    - Application Mail.Send`n    - Application Calendars.Read"
        $yaml = $yaml -replace '  BootstrapMember: GraphAPI-Dummy', "  BootstrapMember: GraphAPI-Dummy`n  ScopeKind: `"Group`"`n  SeparateScopePerRole: `"true`""
        Set-Content $separateConfig -Value $yaml -Encoding UTF8

        $null = Invoke-RBAC4AppConfig -Path $separateConfig -WhatIf

        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-UnifiedGroup -Times 0
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementScope -Times 0
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName New-ManagementRoleAssignment -Times 0
        Should -Invoke -ModuleName EXORBACforAppManagement -CommandName Add-UnifiedGroupLinks -Times 0
    }

